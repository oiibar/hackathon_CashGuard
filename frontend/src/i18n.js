export const I18n = createContext({ lang: 'ru', t: (k) => ru[k] ?? k })

export function makeT(lang) {
  const dict = LANGS[lang] || ru
  return (key, vars) => {
    let s = dict[key] ?? ru[key] ?? key
    if (vars && typeof s === 'string') for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v)
    return s
  }
}

